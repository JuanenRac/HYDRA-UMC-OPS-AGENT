def message_keys() -> tuple[str, ...]:
    return tuple(_CATALOG)


def translate(key: str, language: str = "en", **values: object) -> str:
    """The sentence `key` in `language` with `values` filled in; English when the language or a placeholder is missing."""
    table = _CATALOG.get(key)
    if table is None:
        raise KeyError(f"unknown message {key!r}")
    template = table.get(language if language in LANGUAGES else "en", table["en"])
    try:
        return template.format(**values)
    except (KeyError, IndexError):
        return table["en"].format_map({**{name: "" for name in ("severity", "node", "component", "detail", "count", "project")}, **values})
